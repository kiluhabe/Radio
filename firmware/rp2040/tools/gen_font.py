#!/usr/bin/env python3
"""Rasterize Radio Canada (OFL-1.1) into src/adapters/font_data.rs.

Usage (from firmware/rp2040):
    python3 -I tools/gen_font.py [TTF] [--preview out.png]

Glyph coordinates: pen origin on the baseline; x_off/y_off locate the ink
bitmap's top-left relative to it (y_off is negative above the baseline).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "adapters", "font_data.rs")
DEFAULT_TTF = os.path.join(HERE, "..", "fonts", "RadioCanada.ttf")
AXES = [400, 100]  # Weight, Width
NUMERAL_ZERO_H = 33
LABEL_ZERO_H = 7
NUMERAL_CHARS = "0123456789."
LABEL_CHARS = "MHz"

# Layout (mirrored in display.rs)
NUM_RIGHT = 128
NUM_TOP = 2
LABEL_BASELINE = 56
LABEL_GAP = 1


def load(path, size):
    f = ImageFont.truetype(path, size)
    f.set_variation_by_axes(AXES)
    return f


def size_for_zero(path, h):
    size = 4
    while True:
        f = load(path, size)
        b = f.getbbox("0")
        if b[3] - b[1] >= h:
            return size, f
        size += 1


def glyph(font, ch):
    l, t, r, b = font.getbbox(ch, anchor="ls")
    w, h = r - l, b - t
    full = Image.new("1", (w + 4, h + 4), 0)
    ImageDraw.Draw(full).text((2 - l, 2 - t), ch, font=font, fill=1, anchor="ls")
    ib = full.getbbox()
    img = full.crop(ib)
    x_off, y_off = l + ib[0] - 2, t + ib[1] - 2
    w, h = img.size
    rb = (w + 7) // 8
    data = bytearray()
    px = img.load()
    for y in range(h):
        for bx in range(rb):
            v = 0
            for k in range(8):
                x = bx * 8 + k
                if x < w and px[x, y]:
                    v |= 0x80 >> k
            data.append(v)
    return dict(ch=ch, w=w, h=h, x_off=x_off, y_off=y_off,
                adv=round(font.getlength(ch)), data=bytes(data))


def build(path):
    out = {}
    for name, h, chars in (("NUMERAL", NUMERAL_ZERO_H, NUMERAL_CHARS),
                           ("LABEL", LABEL_ZERO_H, LABEL_CHARS)):
        size, font = size_for_zero(path, h)
        gl = [glyph(font, c) for c in chars]
        out[name] = dict(size=size, font=font, glyphs=gl,
                         ascent=-min(g["y_off"] for g in gl))
    return out


def emit(fonts):
    s = [
        "// @generated by tools/gen_font.py -- do not edit.",
        "// Regenerate (from firmware/rp2040): python3 -I tools/gen_font.py",
        "// Font: Radio Canada, Copyright 2019 The Radio-Canada Project Authors,",
        "// SIL Open Font License 1.1 (fonts/OFL.txt). Weight 400, width 100.",
        "",
        "use crate::adapters::bitmap_font::{Font, Glyph};",
        "",
    ]
    total = 0
    for name, f in fonts.items():
        s.append(f"pub const {name}: Font = Font {{")
        s.append(f"    ascent: {f['ascent']},")
        s.append("    glyphs: &[")
        for g in f["glyphs"]:
            total += len(g["data"])
            d = ", ".join(f"0x{b:02x}" for b in g["data"])
            s.append(
                f"        Glyph {{ ch: '{g['ch']}', width: {g['w']}, "
                f"x_off: {g['x_off']}, y_off: {g['y_off']}, advance: {g['adv']}, "
                f"data: &[{d}] }},"
            )
        s.append("    ],")
        s.append("};")
        s.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(s))
    return total


def compose(fonts, text):
    """Replicate display.rs layout from the generated glyph data."""
    img = Image.new("1", (128, 64), 0)
    num = fonts["NUMERAL"]

    def put(font, s, ox, oy):
        gm = {g["ch"]: g for g in font["glyphs"]}
        x = ox
        for c in s:
            g = gm[c]
            rb = (g["w"] + 7) // 8
            for y in range(g["h"]):
                for xx in range(g["w"]):
                    if g["data"][y * rb + xx // 8] & (0x80 >> (xx % 8)):
                        img.putpixel((x + g["x_off"] + xx, oy + g["y_off"] + y), 1)
            x += g["adv"]

    gm = {g["ch"]: g for g in num["glyphs"]}
    left = gm[text[0]]["x_off"]
    ox = NUM_RIGHT - sum(gm[c]["adv"] for c in text)
    put(num, text, ox, NUM_TOP + num["ascent"])
    lab = {g["ch"]: g for g in fonts["LABEL"]["glyphs"]}
    put(fonts["LABEL"], "MHz", ox + left + LABEL_GAP - lab["M"]["x_off"], LABEL_BASELINE)
    return img


def ink_box(font, text):
    img = Image.new("1", (256, 128), 0)
    ImageDraw.Draw(img).text((20, 80), text, font=font, fill=1, anchor="ls")
    l, t, r, b = img.getbbox()
    return l - 20, r - 20


def reference(fonts, text):
    """Whole-string Pillow render at the same positions (advance-aligned)."""
    img = Image.new("1", (128, 64), 0)
    nf, lf = fonts["NUMERAL"]["font"], fonts["LABEL"]["font"]
    nl, _ = ink_box(nf, text)
    ox = NUM_RIGHT - round(nf.getlength(text))
    d = ImageDraw.Draw(img)
    d.text((ox, NUM_TOP + fonts["NUMERAL"]["ascent"]), text, font=nf, fill=1, anchor="ls")
    ll, _ = ink_box(lf, "MHz")
    d.text((ox + nl + LABEL_GAP - ll, LABEL_BASELINE), "MHz", font=lf, fill=1, anchor="ls")
    return img


def main():
    args = sys.argv[1:]
    preview = None
    if "--preview" in args:
        i = args.index("--preview")
        preview = args[i + 1]
        del args[i:i + 2]
    path = args[0] if args else DEFAULT_TTF
    fonts = build(path)
    total = emit(fonts)
    print(f"sizes: numeral={fonts['NUMERAL']['size']} label={fonts['LABEL']['size']}; "
          f"bitmap bytes={total}")
    if preview:
        sheet = Image.new("L", (128 * 4, 64 * 4 * 2 + 8), 128)
        for n, t in enumerate(("80.0", "108.0")):
            a, r = compose(fonts, t), reference(fonts, t)
            diff = sum(1 for p, q in zip(a.get_flattened_data(), r.get_flattened_data()) if p != q)
            print(f"{t}: pixel diff vs whole-string render = {diff}")
            sheet.paste(a.convert("L").point(lambda v: 255 if v else 0)
                        .resize((512, 256), Image.NEAREST), (0, n * (256 + 8)))
        sheet.save(preview)


if __name__ == "__main__":
    main()
